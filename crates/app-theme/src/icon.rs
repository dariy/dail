//! The icon font (UI-3): a Material Symbols Outlined subset (Apache-2.0) with the `FILL` and `wght`
//! axes; `opsz` fixed at 20 and `GRAD` at 0. The icons are named here with their code points (from
//! the upstream `.codepoints` file); `assets/fonts/README.md` has the command that made the subset.

use serde::{Deserialize, Serialize};

/// The subset of Material Symbols Outlined.
pub const ICON_FONT: &[u8] = include_bytes!("../assets/fonts/MaterialSymbolsOutlined-dail.ttf");

/// Its licence (Apache-2.0).
pub const ICON_LICENSE: &str = include_str!("../assets/fonts/LICENSE-MaterialSymbols.txt");

/// The family name a front-end registers [`ICON_FONT`] under.
pub const ICON_FAMILY: &str = "icons";

